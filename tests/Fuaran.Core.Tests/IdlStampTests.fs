module Fuaran.Core.Tests.IdlStampTests

open System
open System.IO
open System.Security.Cryptography
open System.Text
open System.Text.RegularExpressions
open Expecto
open Fuaran.Core.Idl
open Fuaran.Core.Idl.Codegen.Types

// ---------------------------------------------------------------------------
// Phase 505 — ONE stamp heads every generated artefact, and its policy is a CONTENT HASH.
//
// The generator used to write eight hand-spelled headers. The F# one named the package
// VERSION, so a version cut re-stamped every committed module although no emission had moved;
// the TypeScript ones carried phase labels frozen at first emission; the F* ones no version at
// all. Now each artefact opens with the same stamp (DECISIONS.md, the stamp policy): the
// generator's package name, the target, the vocabulary's identity (a SHA-256 over its canonical
// `idl.json` value) and an `emission` SHA-256 over every byte BELOW the stamp.
//
// THE POLICY, in one sentence: the stamp moves exactly when the vocabulary's canonical value or
// the emitted bytes below it move, never with the generator's version, and the bytes below it
// move only when the emission does.
//
// The verifier here is written independently of the generator's own: it parses the stamp off
// the text and recomputes the hash from the bytes, so a stamp that lied about its emission, a
// hand edit to a committed artefact, or a version creeping back into a header goes red here.
// ---------------------------------------------------------------------------

let private sha256 (text: string) =
    "sha256:"
    + Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes text)).ToLowerInvariant()

/// The stamp's first line, in either comment style. No digit anywhere: no version, no phase.
let private firstLine =
    Regex(
        @"^GENERATED by Fuaran\.Core\.Idl\.Codegen — (F# structural layer|TypeScript module|TypeScript declarations|F\* model|F\* proofs|F\* vectors)\. Do not edit by hand: regenerate it from its inputs\.$"
    )

let private keyLine = Regex(@"^(vocabulary|emission): (sha256:[0-9a-f]{64})$")

type private Parsed =
    { Target: string
      Vocabularies: string list
      Emission: string
      Body: string }

/// Reads a stamp off the head of `text` — a `// ` run or a leading `(*` … `*)` block — and the
/// body below it ([[Snapshots.unstamped]], the one place every suite finds that boundary).
/// `Error` names what did not parse.
let private parse (text: string) : Result<Parsed, string> =
    let body = Snapshots.unstamped text

    let stampLines =
        if body.Length = text.Length then
            []
        else
            match text.Substring(0, text.Length - body.Length - 1).Split '\n' |> List.ofArray with
            | "(*" :: inner ->
                inner
                |> List.truncate (List.length inner - 1)
                |> List.map (fun l -> l.Substring 3)
            | lines -> lines |> List.map (fun l -> l.Substring 3)

    match stampLines with
    | first :: keys when firstLine.IsMatch first ->
        let pairs =
            keys
            |> List.map (fun l ->
                let m = keyLine.Match l

                if m.Success then
                    Some(m.Groups.[1].Value, m.Groups.[2].Value)
                else
                    None)

        if pairs |> List.exists Option.isNone then
            Error(sprintf "a stamp line is not `<key>: sha256:<hex>`: %A" keys)
        else
            let pairs = pairs |> List.choose id

            match pairs |> List.filter (fun (k, _) -> k = "emission") with
            | [ _, emission ] when fst (List.last pairs) = "emission" ->
                Ok
                    { Target = (firstLine.Match first).Groups.[1].Value
                      Vocabularies = pairs |> List.filter (fun (k, _) -> k = "vocabulary") |> List.map snd
                      Emission = emission
                      Body = body }
            | _ -> Error "the stamp's last key is not its one `emission` line"
    | _ -> Error(sprintf "the artefact does not open with a stamp: %A" (text.Split '\n' |> Array.truncate 3))

let private verified (what: string) (text: string) : Parsed =
    match parse (text.Replace("\r\n", "\n")) with
    | Error e -> failtestf "%s: %s" what e
    | Ok p ->
        Expect.isNonEmpty p.Vocabularies (what + ": the stamp names the vocabulary it came from")
        Expect.equal p.Emission (sha256 p.Body) (what + ": the emission hash is over the bytes below the stamp")
        p

let private ok what (r: Result<string, CodegenError>) =
    match r with
    | Ok s -> s
    | Error e -> failtestf "%s refused: %s" what (CodegenError.describe e)

/// The sixteen committed artefacts the stamp heads: nine F# fixtures, seven F* modules.
let private committed =
    [ "tests/Fuaran.Core.Tests/MiniGenerated.fs"
      "tests/Fuaran.Core.Tests/DocGenerated.fs"
      "tests/Fuaran.Core.Tests/DocAnnotatedGenerated.fs"
      "tests/Fuaran.Core.Tests/ScoreGenerated.fs"
      "tests/Fuaran.Core.Tests/ReferenceGenerated.fs"
      "tests/Fuaran.Core.Tests/DeriveGenerated.fs"
      "tests/Fuaran.Core.Tests/DecodeVectorsGenerated.fs"
      "tests/Fuaran.Core.Tests/SpecDecodersGenerated.fs"
      "tests/Fuaran.Core.Tests/RefusalCornersGenerated.fs"
      "proofs/Vocabulary.fst"
      "proofs/VocabularyProofs.fst"
      "proofs/DocVocabulary.fst"
      "proofs/DocVocabularyProofs.fst"
      "proofs/ScoreVocabulary.fst"
      "proofs/ScoreVocabularyProofs.fst"
      "proofs/VocabularyVectors.fst" ]

let private idl = DeriveIdl.deriveIdl
let private tags = idl.Kinds |> List.map _.Tag

let private modelled (v: Idl) =
    FStarTarget.partition v |> List.filter _.Refusal.IsNone |> List.map _.Tag

/// Every target the stamp heads, emitted fresh over one vocabulary.
let private emissions (v: Idl) (moduleName: string) : (string * string) list =
    let ts = v.Kinds |> List.map _.Tag

    [ "F# module", Gen.fsharpModule moduleName v ts |> ok "F# module"
      "F# derived module",
      Gen.fsharpModuleDerived GenSupport.Empty DeriveIdl.derivations moduleName v ts
      |> ok "F# derived module"
      "TypeScript module", Gen.typescriptModule v ts |> ok "TypeScript module"
      "TypeScript derived module",
      Gen.typescriptModuleDerived [ Derivation.StructuralAccess ] v ts
      |> ok "TypeScript derived module"
      "TypeScript declarations", Gen.typescriptDeclarations v ts |> ok "TypeScript declarations"
      "TypeScript derived declarations",
      Gen.typescriptDeclarationsDerived [ Derivation.StructuralAccess ] v ts
      |> ok "TypeScript derived declarations"
      "F* model", FStarTarget.vocabularyModule moduleName v (modelled v) |> ok "F* model"
      "F* proofs",
      FStarTarget.proofsModule (moduleName + "Proofs") moduleName v (modelled v)
      |> ok "F* proofs" ]

[<Tests>]
let tests =
    testList
        "IDL stamp (Phase 505)"
        [ testCase "every committed generated artefact opens with a stamp whose emission hash verifies"
          <| fun _ ->
              for rel in committed do
                  let path = Snapshots.repoFile rel

                  if not (File.Exists path) then
                      failtestf "%s not found at %s" rel path

                  verified rel (File.ReadAllText path) |> ignore

          testCase "every target emits the one stamp, and it verifies"
          <| fun _ ->
              for what, text in emissions idl "StampProbe" do
                  verified what text |> ignore

          testCase "a regeneration from unchanged inputs changes no byte"
          <| fun _ ->
              Expect.equal (emissions idl "StampProbe") (emissions idl "StampProbe") "the same inputs, the same bytes"

          testCase "a changed byte below the stamp no longer matches its emission hash"
          <| fun _ ->
              // The other direction of the hash: a hand edit to a generated artefact is detectable
              // from the artefact alone.
              for what, text in emissions idl "StampProbe" do
                  let p = verified what text
                  let edited = p.Body.Replace("\n", "\n ")
                  Expect.notEqual edited p.Body (what + ": the probe edit changed something")
                  Expect.notEqual (sha256 edited) p.Emission (what + ": an edited body no longer verifies")

          testCase "a changed input changes the stamp's hashes and nothing else in it"
          <| fun _ ->
              // Two inputs moved: the module name (an option the vocabulary does not carry) and an
              // enum's cases (the vocabulary itself).
              let renamed =
                  { idl with
                      Enums = [ Declare.enumOf "Priority" [ "Low"; "Normal"; "High"; "Urgent" ] ] }

              let before = emissions idl "StampProbe"
              let afterName = emissions idl "StampProbeMoved"
              let afterIdl = emissions renamed "StampProbe"

              for (what, a), (_, b), (_, c) in List.zip3 before afterName afterIdl do
                  let pa, pb, pc = verified what a, verified what b, verified what c
                  Expect.equal pb.Target pa.Target (what + ": the target line does not move")
                  // The emission hash moves exactly when the emission does: the TypeScript targets
                  // take no module name, so for them the first move is no move at all.
                  Expect.equal
                      (pb.Emission = pa.Emission)
                      (pb.Body = pa.Body)
                      (what + ": the emission hash moves iff the bytes below it do")

                  Expect.notEqual pc.Vocabularies pa.Vocabularies (what + ": a new vocabulary moves its identity")
                  // A proof script's lemmas are case-generic, so a new enum case can leave it
                  // byte-identical below the stamp; the vocabulary line still moves.
                  Expect.equal
                      (pc.Emission = pa.Emission)
                      (pc.Body = pa.Body)
                      (what + ": and its emission hash moves iff the emission does")

                  // Only the hash lines differ: the stamp's text with its hashes masked is one string.
                  let mask (s: string) =
                      Regex.Replace(
                          s.Substring(0, s.Length - (verified what s).Body.Length),
                          "sha256:[0-9a-f]{64}",
                          "H"
                      )

                  Expect.equal (mask b) (mask a) (what + ": nothing else in the stamp moves with the module name")

          testCase
              "a doc-only vocabulary change moves the stamp's vocabulary line, and below the stamp only what renders the doc"
          <| fun _ ->
              // A doc is part of the vocabulary (it is in `idl.json`), so its identity moves on every
              // target. The TypeScript targets render no doc, so below their stamp nothing moves and
              // neither does the emission hash; the F# module renders it as `///` lines, so its
              // emission moves with them.
              let documented =
                  { idl with
                      Kinds =
                          idl.Kinds
                          |> List.mapi (fun i k ->
                              if i = 0 then
                                  { k with
                                      Fields =
                                          k.Fields
                                          |> List.mapi (fun j f ->
                                              if j = 0 then
                                                  { f with
                                                      Annotations =
                                                          { f.Annotations with
                                                              Doc = Some "A doc only." } }
                                              else
                                                  f) }
                              else
                                  k) }

              for (what, a), (_, b) in List.zip (emissions idl "StampProbe") (emissions documented "StampProbe") do
                  let pa, pb = verified what a, verified what b
                  Expect.notEqual pb.Vocabularies pa.Vocabularies (what + ": the vocabulary line moves with a doc")

                  if what.StartsWith "TypeScript" then
                      Expect.equal
                          pb.Body
                          pa.Body
                          (what + ": a target that renders no doc is identical below the stamp")

                      Expect.equal pb.Emission pa.Emission (what + ": so its emission hash does not move")
                  elif what.StartsWith "F# " then
                      Expect.notEqual pb.Body pa.Body (what + ": the F# module renders the doc")
                      Expect.notEqual pb.Emission pa.Emission (what + ": so its emission hash moves")

          testCase "the vectors module names every vocabulary it covers"
          <| fun _ ->
              let p =
                  verified
                      "proofs/VocabularyVectors.fst"
                      (File.ReadAllText(Snapshots.repoFile "proofs/VocabularyVectors.fst"))

              Expect.equal p.Target "F* vectors" "the vectors target"
              Expect.equal (List.length p.Vocabularies) 3 "one vocabulary line per model it holds facts over"

          testCase "the scaffold's provenance header is the same grammar, keyed by its source wire"
          <| fun _ ->
              let header = Gen.provenanceHeader "//" "abc123" "agent:example"

              Expect.equal
                  header
                  "// AI-scaffolded by Fuaran.Core.Idl.Codegen — scaffold. INERT structure; behaviour is human-bound (named holes, Phase 318).\n// source-wire-hash: abc123\n// actor: agent:example"
                  "one renderer, one grammar" ]
