module Fuaran.Core.Tests.DecisionsTests

// ---------------------------------------------------------------------------
// Phase 501 — `DECISIONS.md` carries a status under every entry and a generated index at its head.
//
// The decision log is where a reader finds the current ruling on a function, and by 2026-10-17 it
// held 161 entries over nearly ten thousand lines with no index and no status: an entry a later one
// amended still read as current at its own heading, and the ordinals within one day were out of
// order. The fix is the README roster's rule (PackageRosterTests): the headings declare, the index
// is a projection of them, and a test holds the two equal. What each decision SAYS stays prose a
// person writes; this file asserts the shape a reader navigates by and nothing else.
//
// The properties, each with a go-red case over synthetic input beside the live one:
//
//   1. Every `## ` heading is an entry heading, `## <yyyy-mm-dd> — D<n>: <title>`, after the index.
//   2. Every entry carries a status line directly under its heading (one blank line between), in
//      the grammar the file's preamble states: clauses `Live`, `Amended-by D<n>[, D<n>…]`,
//      `Superseded-by D<n>`, `Moved-to-compute`, `Never-minted`, joined by `; `, then an optional
//      ` — ` note. `Live` and `Never-minted` stand alone.
//   3. The ordinals run from D1 to the newest with none missing and none repeated (a number never
//      assigned is recorded as `Never-minted`, as D6 is).
//   4. A status naming another entry names one that exists, is newer, and was minted.
//   5. The block between the index markers is byte-equal to the render of the entries, in ordinal
//      order. `CORE_APPROVE_DOCS=DECISIONS` rewrites it (Approval.fs, one truthiness).
//
// So an entry added by any later change is red until it carries its status line and the index has
// been regenerated — which is the whole point: the record a reader trusts is the one the gate reads.
// ---------------------------------------------------------------------------

open System
open System.IO
open System.Text.RegularExpressions
open Expecto

/// One clause of a status line.
type internal Clause =
    | Live
    | AmendedBy of int list
    | SupersededBy of int
    | MovedToCompute
    | NeverMinted

/// One entry, as its heading and status line declare it.
type internal Entry =
    {
        Id: int
        Date: string
        Title: string
        Clauses: Clause list
        /// One-based line of the heading, for messages.
        Line: int
    }

[<Literal>]
let internal BeginPrefix = "<!-- decisions-index:begin"

[<Literal>]
let internal BeginMarker =
    "<!-- decisions-index:begin — generated by DecisionsTests from the headings and their status lines; CORE_APPROVE_DOCS=DECISIONS rewrites it -->"

[<Literal>]
let internal EndMarker = "<!-- decisions-index:end -->"

[<Literal>]
let internal StatusPrefix = "**Status:** "

let private heading =
    Regex(@"^## (\d{4}-\d{2}-\d{2}) — D(\d+): (.+)$", RegexOptions.Compiled)

let private amended =
    Regex(@"^Amended-by (D\d+(?:, D\d+)*)$", RegexOptions.Compiled)

let private superseded = Regex(@"^Superseded-by D(\d+)$", RegexOptions.Compiled)

let private ids (s: string) : int list =
    s.Split([| ", " |], StringSplitOptions.None)
    |> Seq.map (fun d -> int (d.Substring 1))
    |> List.ofSeq

/// Read one clause; `Error` carries the text that is not one.
let internal parseClause (c: string) : Result<Clause, string> =
    match c with
    | "Live" -> Ok Live
    | "Moved-to-compute" -> Ok MovedToCompute
    | "Never-minted" -> Ok NeverMinted
    | _ ->
        let a = amended.Match c

        if a.Success then
            Ok(AmendedBy(ids a.Groups.[1].Value))
        else
            let s = superseded.Match c

            if s.Success then
                Ok(SupersededBy(int s.Groups.[1].Value))
            else
                Error c

/// The clauses of a status value: the text before the first ` — ` (the rest is a note).
let internal parseStatus (value: string) : Result<Clause list, string> =
    let clauses =
        match value.IndexOf " — " with
        | -1 -> value
        | i -> value.Substring(0, i)

    let parsed =
        clauses.Split([| "; " |], StringSplitOptions.None) |> Array.map parseClause

    match
        parsed
        |> Array.tryPick (fun r ->
            match r with
            | Error e -> Some e
            | Ok _ -> None)
    with
    | Some bad -> Error bad
    | None ->
        Ok(
            parsed
            |> Array.choose (fun r ->
                match r with
                | Ok c -> Some c
                | Error _ -> None)
            |> List.ofArray
        )

let internal renderClause (c: Clause) : string =
    match c with
    | Live -> "Live"
    | MovedToCompute -> "Moved-to-compute"
    | NeverMinted -> "Never-minted"
    | AmendedBy ds -> "Amended-by " + (ds |> List.map (sprintf "D%d") |> String.concat ", ")
    | SupersededBy d -> sprintf "Superseded-by D%d" d

/// The lines of the file, split on `\n` only (the file is LF; a stray `\r` is kept and so is red).
let private split (text: string) : string[] = text.Split '\n'

/// Read the file's entries, or every way it fails properties 1 and 2.
let internal parse (text: string) : Result<Entry list, string list> =
    let lines = split text

    let endAt = lines |> Array.tryFindIndex (fun l -> l = EndMarker)

    let errors = ResizeArray<string>()
    let entries = ResizeArray<Entry>()

    match endAt with
    | None -> errors.Add "no index end marker (`<!-- decisions-index:end -->`)"
    | Some _ -> ()

    for i in 0 .. lines.Length - 1 do
        let l = lines.[i]

        if l.StartsWith "## " then
            let m = heading.Match l

            if not m.Success then
                errors.Add(sprintf "line %d: a `## ` heading that is not `## <date> — D<n>: <title>`: %s" (i + 1) l)
            else
                let id = int m.Groups.[2].Value

                if endAt |> Option.exists (fun e -> i < e) then
                    errors.Add(sprintf "line %d: D%d sits above the index" (i + 1) id)

                let status =
                    if
                        i + 2 < lines.Length
                        && lines.[i + 1] = ""
                        && lines.[i + 2].StartsWith StatusPrefix
                    then
                        Some(lines.[i + 2].Substring StatusPrefix.Length)
                    else
                        None

                match status with
                | None ->
                    errors.Add(
                        sprintf
                            "line %d: D%d has no status line — a blank line, then `**Status:** <clauses>`, directly under its heading"
                            (i + 1)
                            id
                    )
                | Some value ->
                    match parseStatus value with
                    | Error bad ->
                        errors.Add(
                            sprintf "line %d: D%d's status carries `%s`, which is no status clause" (i + 3) id bad
                        )
                    | Ok clauses ->
                        entries.Add
                            { Id = id
                              Date = m.Groups.[1].Value
                              Title = m.Groups.[3].Value
                              Clauses = clauses
                              Line = i + 1 }

    if errors.Count = 0 then
        Ok(List.ofSeq entries)
    else
        Error(List.ofSeq errors)

/// Properties 2 (clause combination), 3 and 4 over parsed entries.
let internal check (entries: Entry list) : string list =
    let byId = entries |> List.groupBy (fun e -> e.Id) |> Map.ofList

    [ for e in entries do
          let kinds =
              e.Clauses
              |> List.map (fun c ->
                  match c with
                  | Live -> 0
                  | AmendedBy _ -> 1
                  | SupersededBy _ -> 2
                  | MovedToCompute -> 3
                  | NeverMinted -> 4)

          if List.length (List.distinct kinds) <> List.length kinds then
              yield sprintf "D%d: a status names one clause kind twice" e.Id

          if
              (List.contains Live e.Clauses || List.contains NeverMinted e.Clauses)
              && e.Clauses.Length > 1
          then
              yield sprintf "D%d: `Live` and `Never-minted` stand alone" e.Id

          let named =
              e.Clauses
              |> List.collect (fun c ->
                  match c with
                  | AmendedBy ds -> ds
                  | SupersededBy d -> [ d ]
                  | _ -> [])

          for d in named do
              match Map.tryFind d byId with
              | None -> yield sprintf "D%d: its status names D%d, which is no entry" e.Id d
              | Some(target :: _) when target.Clauses = [ NeverMinted ] ->
                  yield sprintf "D%d: its status names D%d, which was never minted" e.Id d
              | Some _ when d <= e.Id -> yield sprintf "D%d: its status names D%d, which is not newer" e.Id d
              | Some _ -> ()

      for KeyValue(id, es) in byId do
          if es.Length > 1 then
              yield
                  sprintf
                      "D%d is defined %d times (lines %s)"
                      id
                      es.Length
                      (es |> List.map (fun e -> string e.Line) |> String.concat ", ")

      match entries with
      | [] -> yield "no entries were read"
      | _ ->
          let top = entries |> List.map (fun e -> e.Id) |> List.max

          for id in 1..top do
              if not (Map.containsKey id byId) then
                  yield sprintf "D%d is missing — record a number nobody assigned as `Never-minted`" id ]

/// The index block, markers included, from the entries in ordinal order (newest first).
let internal render (entries: Entry list) : string list =
    [ yield BeginMarker
      yield "| Id | Date | Decision | Status |"
      yield "|---|---|---|---|"
      for e in entries |> List.sortByDescending (fun e -> e.Id) do
          yield
              sprintf
                  "| D%d | %s | %s | %s |"
                  e.Id
                  e.Date
                  (e.Title.Replace("|", "\\|"))
                  (e.Clauses |> List.map renderClause |> String.concat "; ")
      yield EndMarker ]

/// The block as the file carries it, markers included; `None` when the markers are not one ordered pair.
let internal block (text: string) : string list option =
    let lines = split text

    let starts =
        lines |> Array.indexed |> Array.filter (fun (_, l) -> l.StartsWith BeginPrefix)

    let ends = lines |> Array.indexed |> Array.filter (fun (_, l) -> l = EndMarker)

    match starts, ends with
    | [| (b, _) |], [| (e, _) |] when b < e -> Some(List.ofArray lines.[b..e])
    | _ -> None

/// The file with its block replaced by `rendered`; `None` when the markers are not one ordered pair.
let internal withBlock (text: string) (rendered: string list) : string option =
    let lines = split text

    match block text with
    | None -> None
    | Some _ ->
        let b = lines |> Array.findIndex (fun l -> l.StartsWith BeginPrefix)
        let e = lines |> Array.findIndex (fun l -> l = EndMarker)

        Some(String.Join("\n", Array.concat [ lines.[.. b - 1]; Array.ofList rendered; lines.[e + 1 ..] ]))

let private path () = Snapshots.repoFile "DECISIONS.md"

/// The well-formed statuses of the go-red sample: three entries, the middle one never minted.
let private okStatus id =
    match id with
    | 1 -> "Amended-by D3 — a note"
    | 2 -> "Never-minted"
    | _ -> "Live"

/// The go-red sample: its index is the render of the WELL-FORMED statuses, and its entries carry
/// `statusOf`, so a case can break one status line and leave everything else current.
let private sample (statusOf: int -> string) : string =
    let body (status: int -> string) =
        [ for id, date, title in [ 3, "2026-10-02", "three"; 2, "2026-10-01", "two"; 1, "2026-10-01", "one" ] do
              yield!
                  [ sprintf "## %s — D%d: %s" date id title
                    ""
                    StatusPrefix + status id
                    ""
                    "Body."
                    "" ] ]

    let entries =
        match
            parse (
                String.Join(
                    "
",
                    "# Log" :: "" :: EndMarker :: "" :: body okStatus
                )
            )
        with
        | Ok es -> es
        | Error es -> failwithf "the well-formed sample does not parse: %A" es

    String.Join(
        "
",
        [ "# Log"; "" ] @ render entries @ [ "" ] @ body statusOf
    )

let private errorsOf (text: string) : string list =
    match parse text with
    | Error es -> es
    | Ok entries -> check entries

[<Tests>]
let tests =
    testList
        "Decisions"
        [ testCase "every entry carries a status, the numbers are whole, and the index equals the headings"
          <| fun _ ->
              Approval.validate Approval.Docs
              let p = path ()
              let text = File.ReadAllText p

              let entries =
                  match parse text with
                  | Ok es -> es
                  | Error es -> failtestf "DECISIONS.md:\n  %s" (String.concat "\n  " es)

              Expect.isGreaterThan entries.Length 150 "the log was read — it holds every entry since D1"
              Expect.isEmpty (check entries) "DECISIONS.md: the statuses and numbering"

              let rendered = render entries

              match block text with
              | None ->
                  failtestf
                      "DECISIONS.md carries no single ordered pair of index markers (%s … %s)"
                      BeginPrefix
                      EndMarker
              | Some current when current = rendered -> ()
              | Some _ when Approval.admits Approval.Docs Approval.Files.Decisions ->
                  Approval.write Approval.Docs Approval.Files.Decisions p (Option.get (withBlock text rendered))
                  |> ignore
              | Some current ->
                  let differing =
                      List.zip
                          (List.truncate (min current.Length rendered.Length) current)
                          (List.truncate (min current.Length rendered.Length) rendered)
                      |> List.tryFind (fun (a, b) -> a <> b)

                  failtestf
                      "DECISIONS.md's index is not the render of its headings (%d lines carried, %d rendered; first difference: %A). Regenerate with CORE_APPROVE_DOCS=DECISIONS and a run of --filter Decisions, then stage the file."
                      current.Length
                      rendered.Length
                      differing

          testCase "go-red: a heading with no status line is named"
          <| fun _ ->
              let text = (sample okStatus).Replace(StatusPrefix + "Live\n", "")
              let errs = errorsOf text
              Expect.exists errs (fun e -> e.Contains "D3 has no status line") (sprintf "%A" errs)

          testCase "go-red: an index row that disagrees with its heading is caught"
          <| fun _ ->
              let text = sample okStatus
              let entries = Result.defaultWith (fun es -> failtestf "%A" es) (parse text)
              Expect.equal (block text) (Some(render entries)) "the sample's block is current"

              let drifted =
                  text.Replace("| D3 | 2026-10-02 | three | Live |", "| D3 | 2026-10-02 | three | Moved-to-compute |")

              Expect.notEqual (block drifted) (Some(render entries)) "a changed row is not the render"
              let missing = text.Replace("| D2 | 2026-10-01 | two | Never-minted |\n", "")
              Expect.notEqual (block missing) (Some(render entries)) "a dropped row is not the render"

          testCase "go-red: a clause outside the grammar, a reference that is not newer, and a lone clause combined"
          <| fun _ ->
              let bad id =
                  match id with
                  | 1 -> "Amended by D3"
                  | 2 -> "Never-minted"
                  | _ -> "Live"

              Expect.exists (errorsOf (sample bad)) (fun e -> e.Contains "no status clause") "spelling"

              let older id =
                  match id with
                  | 3 -> "Amended-by D1"
                  | 2 -> "Never-minted"
                  | _ -> "Live"

              Expect.exists (errorsOf (sample older)) (fun e -> e.Contains "not newer") "direction"

              let unminted id =
                  match id with
                  | 1 -> "Superseded-by D2"
                  | 2 -> "Never-minted"
                  | _ -> "Live"

              Expect.exists (errorsOf (sample unminted)) (fun e -> e.Contains "never minted") "a never-minted target"

              let combined id =
                  match id with
                  | 1 -> "Live; Moved-to-compute"
                  | 2 -> "Never-minted"
                  | _ -> "Live"

              Expect.exists (errorsOf (sample combined)) (fun e -> e.Contains "stand alone") "Live alone"
              Expect.isEmpty (errorsOf (sample okStatus)) "and the well-formed sample is clean"

          testCase "go-red: a skipped number, a repeated number and a stray heading"
          <| fun _ ->
              let text = sample okStatus

              let skipped =
                  text.Replace("## 2026-10-01 — D2: two\n\n" + StatusPrefix + "Never-minted\n\nBody.\n\n", "")

              Expect.exists (errorsOf skipped) (fun e -> e.Contains "D2 is missing") "a gap"

              let repeated = text.Replace("D3: three", "D1: three")
              Expect.exists (errorsOf repeated) (fun e -> e.Contains "D1 is defined 2 times") "a repeat"

              let stray = text + "\n## Forward-looking notes\n"
              Expect.exists (errorsOf stray) (fun e -> e.Contains "not `## <date>") "a non-entry heading"

          testCase "the status grammar reads what the file's preamble states"
          <| fun _ ->
              Expect.equal (parseStatus "Live") (Ok [ Live ]) "Live"
              Expect.equal (parseStatus "Live — restated") (Ok [ Live ]) "a note is not a clause"

              Expect.equal
                  (parseStatus "Moved-to-compute; Amended-by D66, D69")
                  (Ok [ MovedToCompute; AmendedBy [ 66; 69 ] ])
                  "two clauses"

              Expect.equal (parseStatus "Superseded-by D9") (Ok [ SupersededBy 9 ]) "superseded"
              Expect.equal (parseStatus "Amended-by D9,D10") (Error "Amended-by D9,D10") "the list separator is `, `"

              for s in
                  [ "Live"
                    "Amended-by D28, D51"
                    "Superseded-by D9"
                    "Moved-to-compute"
                    "Never-minted" ] do
                  match parseStatus s with
                  | Ok [ c ] -> Expect.equal (renderClause c) s "a clause renders as it reads"
                  | other -> failtestf "%s read as %A" s other ]
