/// Phase 723 (DECISIONS.md D190, D256, D288) — one vocabulary declaring every canonical-form shape a
/// generated host applies: a member's aliases at each position a member can hold one (a kind's member,
/// a record's, a union case's), an enum case's aliases, and each of the four presence conditions, one of
/// them over an aliased sibling and one over an int sibling a whole number written as a float token does
/// not satisfy. The sampled-mutation law (`IdlRefusalHostTests`) reads its documents through the
/// interpreter, the compiled F# host and the TypeScript host, respelling members and enum values under
/// their aliases before it mutates them.
